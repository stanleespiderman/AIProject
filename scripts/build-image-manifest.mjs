writeFileSync(out, header + JSON.stringify(images, null, 2) + ";\n");
const count = Object.values(images).reduce((n, v) => n + v.length, 0);
console.log(`Wrote ${count} images for ${Object.keys(images).length} exercises to src/data/exerciseImages.ts`);
