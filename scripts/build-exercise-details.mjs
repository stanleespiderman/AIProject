#!/usr/bin/env node
/**
 * Compiles docs/data/whatnext-exercise-form-data.json (the source of truth for
 * form content) into src/data/exerciseDetails.ts.
 *
 *   npm run build:details
 *
 * Edit the JSON (for example to set review.status to "approved"), then re-run.
 * Never edit exerciseDetails.ts by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "docs/data/whatnext-exercise-form-data.json");
const out = join(root, "src/data/exerciseDetails.ts");

const data = JSON.parse(readFileSync(src, "utf8"));
const REQUIRED = [
  "id", "movementPattern", "isStaticHold", "muscles", "equipmentDetail", "setup", "execution",
  "breathing", "formCues", "commonMistakes", "safety", "rest", "easierOption", "harderOption",
  "image", "review",
];

const details = {};
for (const e of data.exercises) {
  for (const key of REQUIRED) {
    if (e[key] === undefined) throw new Error(`${e.id ?? "?"}: missing "${key}"`);
  }
  if (details[e.id]) throw new Error(`duplicate id ${e.id}`);
  if (e.formCues.length !== 3) throw new Error(`${e.id}: expected 3 formCues, got ${e.formCues.length}`);
  details[e.id] = {
    movementPattern: e.movementPattern,
    isStaticHold: e.isStaticHold,
    muscles: e.muscles,
    equipmentDetail: e.equipmentDetail,
    setup: e.setup,
    execution: e.execution,
    breathing: e.breathing,
    formCues: e.formCues,
    commonMistakes: e.commonMistakes,
    safety: e.safety,
    rest: e.rest,
    easierOption: e.easierOption,
    harderOption: e.harderOption,
    image: e.image,
    reviewStatus: e.review.status === "approved" ? "approved" : "pending",
  };
}

const header = `// AUTO-GENERATED by scripts/build-exercise-details.mjs. DO NOT EDIT BY HAND.
// Source of truth: docs/data/whatnext-exercise-form-data.json (v${data.version}, ${data.generated}).
// Regenerate with: npm run build:details
import type { ExerciseDetails } from "@/lib/types";

/** Form, safety and image content keyed by exercise id. Every id in EXERCISES must appear here. */
export const EXERCISE_DETAILS: Record<string, ExerciseDetails> = `;

writeFileSync(out, header + JSON.stringify(details, null, 2) + ";\n");
console.log(`Wrote ${Object.keys(details).length} entries to ${out}`);
