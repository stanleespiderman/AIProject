#!/usr/bin/env node
/**
 * Lists the illustrations in public/exercises/ and writes src/data/exerciseImages.ts,
 * so a tile shows an image only when one has been uploaded for that exercise.
 *
 *   npm run build:images     (also runs before `npm run build`)
 *
 * Name each file after the exercise id: public/exercises/<exercise-id>.png (or .webp, .jpg).
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public/exercises");
const out = join(root, "src/data/exerciseImages.ts");

const EXT = new Set([".png", ".webp", ".jpg", ".jpeg"]);
const images = {};
for (const file of readdirSync(dir).sort()) {
  const ext = extname(file).toLowerCase();
  if (!EXT.has(ext)) continue;
  const id = file.slice(0, -ext.length);
  if (images[id]) throw new Error(`Two images for "${id}": ${images[id]} and /exercises/${file}`);
  images[id] = `/exercises/${file}`;
}

const body = Object.entries(images)
  .map(([id, path]) => `  ${JSON.stringify(id)}: ${JSON.stringify(path)},`)
  .join("\n");

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-exercise-images.mjs. DO NOT EDIT BY HAND.
// Lists the files in public/exercises/. Regenerate with: npm run build:images

/** Exercise id to image path. Exercises without an entry are shown without an image. */
export const EXERCISE_IMAGES: Record<string, string> = {
${body}
};
`,
);
console.log(`Found ${Object.keys(images).length} exercise image(s)`);
